   public static int hue(float h) {
      return 16777215 & Color.HSBtoRGB(h - (float)Math.floor((double)h), 0.9F, 1.0F);
   }

   public static int color(int style, float pos, float time) {
      if (style <= 0) {
         return hue(pos + time);
      } else {
         int[] palette = PALETTES[(style - 1) % PALETTES.length];
         float x = pos + time;
         x -= (float)Math.floor((double)x);
         float scaled = x * (float)palette.length;
         int i = (int)Math.floor((double)scaled) % palette.length;
         int j = (i + 1) % palette.length;
         float f = scaled - (float)Math.floor((double)scaled);
         return FSColors.lerp(palette[i], palette[j], f);
      }
   }
