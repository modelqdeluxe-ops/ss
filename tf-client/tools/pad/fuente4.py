def text_pixels(s):
    pts, x = set(), 0
    for ch in s:
        g = G[ch]
        for y, row in enumerate(g):
            for dx, c in enumerate(row):
                if c == '#':
                    pts.add((x + dx, y))
        x += len(g[0]) + 1
    return x - 1, pts
