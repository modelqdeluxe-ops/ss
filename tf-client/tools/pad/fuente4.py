# Letras con tilde: dos filas de acento encima de la letra (la celda del atlas mide 10 de alto: 2 de acento + 7 + 1).
ACCENTS = {
    'Á': ('A', ["..#.", ".#.."]), 'É': ('E', ["..#.", ".#.."]), 'Í': ('I', ["..#", ".#."]),
    'Ó': ('O', ["..#.", ".#.."]), 'Ú': ('U', ["..#.", ".#.."]), 'Ü': ('U', ["#..#", "...."]),
    'Ñ': ('N', [".##.#", "#..#."]),
}


def glyph10(ch):
    """La letra en 10 filas (2 de acento, 7 de letra, 1 vacía)."""
    if ch in ACCENTS:
        base, top = ACCENTS[ch]
        return top + G[base] + ['.' * len(G[base][0])]
    g = G[ch]
    return ['.' * len(g[0])] * 2 + g + ['.' * len(g[0])]


def text_pixels(s):
    pts, x = set(), 0
    for ch in s:
        g = G[ch]
        for y, row in enumerate(g):
            for dx, c in enumerate(row):
                if c == '#':
                    pts.add((x + dx, y))
        x += len(g[0]) + 1
    return x - 1, pts
